/* ────────────────────────────────────────────────────────────────────────── */
/*  Fallback colours for old Android web views.                                */
/*                                                                             */
/*  Tailwind writes "bg-[var(--danger)]/15" as color-mix(), and for browsers   */
/*  without color-mix (Android System WebView older than Chromium 111) it      */
/*  falls back to the OPAQUE colour: an error box becomes a red slab with red  */
/*  text on it, the active tab a solid lime block. This builds the same        */
/*  classes as plain rgb() with alpha, used only where color-mix is missing.   */
/*  Pure: scripts/legacy-colors.mjs writes the CSS, a test keeps it current.   */
/* ────────────────────────────────────────────────────────────────────────── */

/** Tokens whose value is fixed (from globals.css :root). Variable ones map to a neutral. */
export const TOKEN_HEX: Record<string, string> = {
  background: "#0b0b0c",
  foreground: "#ffffff",
  "surface-1": "#141416",
  "surface-2": "#1a1b1e",
  "surface-3": "#222327",
  "surface-4": "#2b2c31",
  accent: "#c6f736",
  lime: "#c6f736",
  live: "#c6f432",
  danger: "#ff4d6d",
  warning: "#ffc247",
  completed: "#b392ff",
  gold: "#ffd166",
  muted: "#323338",
  "muted-text": "#aeb0b8",
  social: "#49d9c9",
  sky: "#49d9c9",
  defender: "#49d9c9",
  blocker: "#8f86ff",
  compete: "#ffc247",
  ace: "#ffc247",
  love: "#ff4f7b",
  border: "#26272b",
}

/** Per-area colours (tone, nav tone): no single value, so a soft white. */
const NEUTRAL = "#ffffff"

const PROPS: Record<string, string> = {
  bg: "background-color",
  text: "color",
  ring: "--tw-ring-color",
  border: "border-color",
}

export function rgba(hex: string, alpha: number): string {
  const n = parseInt(hex.slice(1), 16)
  const a = Math.round(alpha * 1000) / 1000
  return `rgb(${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255} / ${a})`
}

/** Escape a class name for a CSS selector (Tailwind's own escaping). */
export function escapeClass(cls: string): string {
  return cls.replace(/[^a-zA-Z0-9_-]/g, (c) => `\\${c}`)
}

export interface LegacyRule {
  cls: string
  prop: string
  value: string
}

const OPACITY = /\b(bg|text|ring|border)-\[var\(--([a-z0-9-]+)\)\]\/(\d{1,3})\b/g
const MIX = /\b(bg|text|ring|border)-\[color-mix\(in_srgb,var\(--([a-z0-9-]+)\)_(\d{1,3})%,transparent\)\]/g

/** Every opacity-on-variable colour class in a piece of source code. */
export function findLegacyRules(source: string): LegacyRule[] {
  const out: LegacyRule[] = []
  for (const re of [OPACITY, MIX]) {
    for (const m of source.matchAll(re)) {
      const [cls, kind, token, pct] = m
      const hex = TOKEN_HEX[token] ?? NEUTRAL
      const alpha = TOKEN_HEX[token] ? Number(pct) / 100 : Math.min(0.12, Number(pct) / 100)
      out.push({ cls, prop: PROPS[kind], value: rgba(hex, alpha) })
    }
  }
  return out
}

/** The whole fallback stylesheet for the given rules (deduplicated, sorted). */
export function buildLegacyCss(rules: LegacyRule[]): string {
  const unique = new Map(rules.map((r) => [r.cls, r]))
  const body = [...unique.values()]
    .sort((a, b) => a.cls.localeCompare(b.cls))
    .map((r) => `  .${escapeClass(r.cls)} { ${r.prop}: ${r.value}; }`)
    .join("\n")
  return `/* GENERATED by scripts/legacy-colors.mjs: do not edit by hand.
   Old Android web views (no color-mix) get these translucent colours instead
   of Tailwind's opaque fallback. Unlayered, so they beat the utilities. */
@supports not (color: color-mix(in lab, red, red)) {
  :root {
    --accent-soft: ${rgba(TOKEN_HEX.accent, 0.14)};
    --accent-line: ${rgba(TOKEN_HEX.accent, 0.32)};
    --tone-soft: ${rgba(NEUTRAL, 0.08)};
    --tone-line: ${rgba(NEUTRAL, 0.2)};
    --shadow-glow: 0 0 0 1px ${rgba(TOKEN_HEX.accent, 0.32)}, 0 14px 36px -10px ${rgba(TOKEN_HEX.accent, 0.55)};
  }
  .glass { background: ${rgba(TOKEN_HEX["surface-2"], 0.72)}; }
${body}
}
`
}
